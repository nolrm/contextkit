const fs = require('fs-extra');
const path = require('path');

const { findSkill } = require('../skills/registry');
const { RETIRED_SKILLS } = require('../skills/retired');

// Stale-context check — deterministic, no AI. Finds instructions that point at
// things that no longer exist (files, skills) and always-loaded context that has
// grown past a budget. Stale context is wrong context: the model follows it.

const MARKER_START = /<!-- Generated by (?:ContextKit|Vibe Kit)[^>]*-->/;
const MARKER_END = /<!-- End (?:ContextKit|Vibe Kit) -->/;

const BRIDGE_FILES = [
  'AGENTS.md',
  'CLAUDE.md',
  'GEMINI.md',
  'CONVENTIONS.md',
  '.windsurfrules',
  '.github/copilot-instructions.md',
];
const RULE_DIRS = ['.claude/rules', '.cursor/rules', '.github/instructions'];
const DEFAULT_BUDGET_LINES = 400;

async function listMarkdown(dir) {
  if (!(await fs.pathExists(dir))) return [];
  const out = [];
  for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await listMarkdown(full)));
    else if (/\.(md|mdc)$/.test(entry.name)) out.push(full);
  }
  return out;
}

/**
 * Removes ContextKit-generated blocks — ck update owns that text, so stale
 * references inside it are fixed by updating, not by the user.
 */
function stripGenerated(content) {
  let result = content;
  for (;;) {
    const start = result.search(MARKER_START);
    if (start === -1) return result;
    const rest = result.slice(start);
    const endMatch = rest.match(MARKER_END);
    if (!endMatch) return result.slice(0, start);
    result = result.slice(0, start) + rest.slice(endMatch.index + endMatch[0].length);
  }
}

function findPathRefs(content) {
  const refs = new Set();
  const regex = /(\.contextkit\/[\w./-]+\.(?:md|mdc|ya?ml|json))/g;
  let match;
  while ((match = regex.exec(content)) !== null) refs.add(match[1].replace(/[.,)]+$/, ''));
  return [...refs];
}

function findSkillRefs(content) {
  const refs = new Set();
  const regex = /`[/$]?([a-z][a-z0-9-]*)`\s+skill\b/g;
  let match;
  while ((match = regex.exec(content)) !== null) refs.add(match[1]);
  return [...refs];
}

function skillStatus(name) {
  const entry = findSkill(name);
  if (entry && /^\[Deprecated/.test(entry.description)) return 'deprecated';
  if (entry) return 'ok';
  if (RETIRED_SKILLS[name]) return 'retired';
  return 'ok'; // unknown names may be the project's own skills
}

/**
 * Counts lines Claude Code always loads: CLAUDE.md (or AGENTS.md when there's
 * no CLAUDE.md), one level of @imports, and .claude/rules files without paths.
 */
async function alwaysLoadedLines(cwd) {
  const read = async (rel) => {
    const full = path.join(cwd, rel);
    return (await fs.pathExists(full)) ? fs.readFile(full, 'utf-8') : null;
  };
  const countLines = (text) => (text ? text.split('\n').length : 0);

  const root = (await read('CLAUDE.md')) ?? (await read('AGENTS.md'));
  let total = countLines(root);
  const seen = new Set();
  const imports = root ? [...root.matchAll(/^@([\w./-]+)\s*$/gm)].map((m) => m[1]) : [];
  for (const rel of imports) {
    if (seen.has(rel)) continue;
    seen.add(rel);
    const text = await read(rel);
    total += countLines(text);
    // AGENTS.md imported from CLAUDE.md can import further files
    if (text && rel === 'AGENTS.md') {
      for (const nested of [...text.matchAll(/^@([\w./-]+)\s*$/gm)].map((m) => m[1])) {
        if (seen.has(nested)) continue;
        seen.add(nested);
        total += countLines(await read(nested));
      }
    }
  }

  for (const file of await listMarkdown(path.join(cwd, '.claude/rules'))) {
    const text = await fs.readFile(file, 'utf-8');
    if (!/^---[\s\S]*?^paths:/m.test(text)) total += countLines(text);
  }
  return total;
}

/**
 * Runs every stale-context check.
 * @param {{cwd?: string, budgetLines?: number}} [options]
 * @returns {Promise<string[]>} warnings
 */
async function checkContext({ cwd = '.', budgetLines = DEFAULT_BUDGET_LINES } = {}) {
  const warnings = [];
  const files = [];
  for (const rel of BRIDGE_FILES) {
    if (await fs.pathExists(path.join(cwd, rel))) files.push(rel);
  }
  for (const dir of [...RULE_DIRS, '.contextkit/standards']) {
    for (const full of await listMarkdown(path.join(cwd, dir))) {
      // contextkit-* rule files and standards/README.md are rewritten by
      // ck update — stale text there is fixed by updating, not by hand.
      const name = path.basename(full);
      if (name.startsWith('contextkit-')) continue;
      if (dir === '.contextkit/standards' && name === 'README.md') continue;
      files.push(path.relative(cwd, full));
    }
  }

  for (const rel of files) {
    const content = stripGenerated(await fs.readFile(path.join(cwd, rel), 'utf-8'));

    for (const ref of findPathRefs(content)) {
      if (ref.includes('*')) continue;
      if (!(await fs.pathExists(path.join(cwd, ref)))) {
        warnings.push(`${rel} points to a missing file: ${ref}`);
      }
    }

    for (const name of findSkillRefs(content)) {
      const status = skillStatus(name);
      if (status === 'retired') {
        warnings.push(
          `${rel} refers to the removed \`${name}\` skill — use ${RETIRED_SKILLS[name]} instead`
        );
      } else if (status === 'deprecated') {
        warnings.push(`${rel} refers to the deprecated \`${name}\` skill (removed in 2.0)`);
      }
    }
  }

  const lines = await alwaysLoadedLines(cwd);
  if (lines > budgetLines) {
    warnings.push(
      `Always-loaded context is ${lines} lines (budget ${budgetLines}) — move topic detail into path-scoped rules`
    );
  }

  return warnings;
}

module.exports = {
  checkContext,
  stripGenerated,
  findPathRefs,
  findSkillRefs,
  alwaysLoadedLines,
  DEFAULT_BUDGET_LINES,
};
