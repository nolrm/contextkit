const fs = require('fs-extra');
const path = require('path');

const { stripHeadline } = require('./headline');
const { checkContext } = require('./context-check');

// After `ck update`, lists everything that needs a human (or /ck update) to
// decide — the CLI never moves user content or deletes work in progress on its
// own. Recomputed on every update; removed when nothing is left.

const CLEANUP_PATH = '.contextkit/pending-cleanup.md';
const MARKER_START = /<!-- Generated by (?:ContextKit|Vibe Kit)[^>]*-->/;
const MARKER_END = /<!-- End (?:ContextKit|Vibe Kit) -->/;

/** CLAUDE.md text outside the ContextKit block and the headline block. */
function customClaudeContent(content) {
  let rest = stripHeadline(content);
  const start = rest.search(MARKER_START);
  if (start !== -1) {
    const tail = rest.slice(start);
    const end = tail.match(MARKER_END);
    rest = rest.slice(0, start) + (end ? tail.slice(end.index + end[0].length) : '');
  }
  return rest.trim();
}

async function hasPendingStandardsUpdates(cwd) {
  const configPath = path.join(cwd, '.contextkit/config.yml');
  if (!(await fs.pathExists(configPath))) return false;
  const content = await fs.readFile(configPath, 'utf-8');
  return /^pending_standards_updates:\s*\n[ \t]+-/m.test(content);
}

/**
 * @param {string} [cwd]
 * @returns {Promise<{id: string, title: string, detail: string}[]>}
 */
async function collectCleanupItems(cwd = '.') {
  const items = [];
  const exists = (rel) => fs.pathExists(path.join(cwd, rel));

  if (await exists('CLAUDE.md')) {
    const custom = customClaudeContent(await fs.readFile(path.join(cwd, 'CLAUDE.md'), 'utf-8'));
    if (custom) {
      const preview = custom.split('\n').slice(0, 6).join('\n');
      items.push({
        id: 'claude-custom-content',
        title: 'Custom content in CLAUDE.md',
        detail: `CLAUDE.md now imports AGENTS.md. Decide per block: move to AGENTS.md (all tools), keep in CLAUDE.md (Claude-only), or delete.\n\n\`\`\`markdown\n${preview}\n\`\`\``,
      });
    }
  }

  if (await exists('.contextkit/squad')) {
    items.push({
      id: 'squad-handoff',
      title: 'Squad state in .contextkit/squad/',
      detail:
        'Squad was removed in 2.0. Convert unfinished tasks to a goal (`/goal`), archive, or keep.',
    });
  }

  if (await exists('.contextkit/spec')) {
    items.push({
      id: 'spec-folder',
      title: 'Spec scopes in .contextkit/spec/',
      detail: 'Spec was removed in 2.0. Convert open stories to goals, archive, or keep.',
    });
  }

  if (await exists('.github/workflows/squad-issue.yml')) {
    items.push({
      id: 'squad-ci-workflow',
      title: 'Squad CI workflow (.github/workflows/squad-issue.yml)',
      detail: 'It runs the removed squad pipeline and will fail. Delete it or keep it.',
    });
  }

  if (await hasPendingStandardsUpdates(cwd)) {
    items.push({
      id: 'pending-standards-updates',
      title: 'Pending standards updates',
      detail:
        '`pending_standards_updates` in config.yml lists upstream fixes that could not be applied automatically because the file was customised.',
    });
  }

  const stale = await checkContext({ cwd });
  if (stale.length > 0) {
    items.push({
      id: 'stale-context',
      title: 'Stale references',
      detail: stale.map((w) => `- ${w}`).join('\n'),
    });
  }

  return items;
}

function renderCleanup(items) {
  const sections = items.map((item) => `## ${item.title}\n\n${item.detail}`).join('\n\n');
  return `# Pending Cleanup

\`ck update\` finished the mechanical part of the upgrade. These need a decision — run \`/ck update\` in Claude Code or Codex and it will walk through each one, then delete this file.

${sections}
`;
}

/**
 * Writes (or removes) .contextkit/pending-cleanup.md.
 * @returns {Promise<{id: string, title: string, detail: string}[]>} items written
 */
async function writeCleanupFile(cwd = '.') {
  const items = await collectCleanupItems(cwd);
  const file = path.join(cwd, CLEANUP_PATH);
  if (items.length === 0) {
    if (await fs.pathExists(file)) await fs.remove(file);
    return items;
  }
  await fs.ensureDir(path.dirname(file));
  await fs.writeFile(file, renderCleanup(items));
  return items;
}

module.exports = {
  CLEANUP_PATH,
  customClaudeContent,
  collectCleanupItems,
  renderCleanup,
  writeCleanupFile,
};
